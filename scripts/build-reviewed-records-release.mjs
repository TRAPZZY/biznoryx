import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const artifact = resolve(root, "db/releases/reviewed-records-0035-0038.sql");
const migrations = [
  "0035_reviewed_imports.sql",
  "0036_money_trail.sql",
  "0037_monthly_close.sql",
  "0038_review_updates.sql",
];
export function buildReviewedRecordsRelease() {
  const parts = migrations.map((name) => {
    const sql = readFileSync(resolve(root, "db/migrations", name), "utf8")
      .replaceAll("\r\n", "\n")
      .trim();
    assert.match(sql, /^begin;\s/i);
    assert.match(sql, /\scommit;$/i);
    return "-- Canonical migration: " + name + "\n" + sql.slice(6, -7).trim();
  });
  return (
    "-- Generated by scripts/build-reviewed-records-release.mjs; do not edit.\n" +
    PRE +
    parts.join("\n\n") +
    "\n\n" +
    POST
  );
}
const PRE = String.raw`\set ON_ERROR_STOP on
\if :{?biznoryx_runtime_role}
\else
  \echo 'Supply the verified existing runtime role with -v biznoryx_runtime_role=ROLE. Do not use a guessed role.'
  \quit 2
\endif
begin;
set local search_path=public,pg_temp;
set local lock_timeout='2s';
set local statement_timeout='30s';
select set_config('app.review_runtime_role', :'biznoryx_runtime_role', true) is not null;
do $$
declare runtime_role record;
begin
  select rolname,rolsuper,rolbypassrls into runtime_role from pg_roles where rolname=current_setting('app.review_runtime_role');
  if runtime_role.rolname is null or runtime_role.rolsuper or runtime_role.rolbypassrls or runtime_role.rolname=current_user then
    raise exception 'A verified, separate, restricted runtime role is required. Do not modify ownership or credentials through this release.';
  end if;
  if pg_has_role(runtime_role.rolname, current_user, 'USAGE') then
    raise exception 'Runtime must not inherit migration administrator ownership';
  end if;
  if not exists(select 1 from pg_roles where rolname=current_user and (rolsuper or rolbypassrls)) then
    raise exception 'Use the existing migration administrator with cross-tenant function ownership';
  end if;
  if to_regclass('public.ingestion_runs') is null or to_regclass('public.manual_entry_period_sources') is null
    or to_regclass('public.evidence_report_definitions') is null or to_regclass('public.notification_events') is null
    or to_regprocedure('public.deliver_source_updates(integer)') is null then
    raise exception 'A required existing schema component is missing. Inspect compatibility; do not replay historical migrations blindly.';
  end if;
  if to_regclass('public.ingestion_import_manifests') is not null or to_regclass('public.money_trail_records') is not null
    or to_regclass('public.monthly_close_versions') is not null then
    raise exception 'This release is already partly or fully installed. Inspect it instead of rerunning this bundle.';
  end if;
end $$;

`;
const POST = String.raw`do $$
declare role_name text:=current_setting('app.review_runtime_role'); inherited_grant record; object_name text;
  objects text[]:=array['business_review_release','import_profiles','ingestion_import_manifests',
    'money_trail_imports','money_trail_records','money_trail_record_states','money_trail_classifications',
    'money_trail_import_records','money_trail_allocations','money_trail_reversals','money_trail_source_supersessions',
    'monthly_source_sets','monthly_required_sources','monthly_close_versions','monthly_close_approvals'];
begin
  -- Limit only these new tables. Preserve existing ACLs, role memberships and provider defaults.
  for inherited_grant in
    select distinct c.relname,a.grantee from pg_class c join pg_namespace n on n.oid=c.relnamespace
    cross join lateral aclexplode(coalesce(c.relacl,acldefault('r',c.relowner))) a
    where n.nspname='public' and c.relname=any(objects) and a.grantee<>c.relowner
      and case when a.grantee=0 then true else pg_has_role(role_name,a.grantee,'USAGE') end
  loop
    if inherited_grant.grantee=0 then
      execute format('revoke all on table public.%I from public',inherited_grant.relname);
    else
      execute format('revoke all on table public.%I from %I',inherited_grant.relname,pg_get_userbyid(inherited_grant.grantee));
    end if;
  end loop;
  foreach object_name in array objects loop
    if pg_has_role(role_name,(select relowner from pg_class where oid=to_regclass('public.'||object_name)),'USAGE') then
      raise exception 'Runtime must not inherit ownership of review tables';
    end if;
  end loop;
  execute format('grant select on business_review_release to %I',role_name);
  execute format('grant select,insert on import_profiles,ingestion_import_manifests,
    money_trail_imports,money_trail_records,money_trail_record_states,money_trail_classifications,
    money_trail_import_records,money_trail_allocations,money_trail_reversals,money_trail_source_supersessions,
    monthly_source_sets,monthly_required_sources,monthly_close_versions,monthly_close_approvals to %I',role_name);
  execute format('grant update(version,kind,payment_status,due_date,reference_confirmed) on money_trail_record_states to %I',role_name);
  execute format('grant execute on function money_trail_member(uuid,boolean) to %I',role_name);
  if has_table_privilege(role_name,'business_review_release','INSERT,UPDATE,DELETE,TRUNCATE') then
    raise exception 'Runtime cannot activate or clear the release control';
  end if;
end $$;
commit;
`;

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const sql = buildReviewedRecordsRelease();
  if (process.argv.includes("--write")) writeFileSync(artifact, sql);
  else if (process.argv.includes("--check"))
    assert.equal(
      readFileSync(artifact, "utf8").replaceAll("\r\n", "\n"),
      sql.replaceAll("\r\n", "\n"),
      "Regenerate the reviewed release SQL after canonical migration changes.",
    );
  else process.stdout.write(sql);
}
